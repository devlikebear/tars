	writeFakeOnboardingConfig(t, wsAbs)

	state := &initMockState{}
	swapInitResetHooks(t, state)
	initRuntimeGOOS = "linux"

	// Pipe an empty answer (just newline) — should be treated as "no".
	stdin := strings.NewReader("\n")
