func TestPickInitResetAPIAddr_PriorityOrder(t *testing.T) {
	cases := []struct {
		name string
		opts initResetOptions
		prev string
		want string
	}{
		{"explicit api-addr wins", initResetOptions{apiAddr: "127.0.0.1:55555"}, "127.0.0.1:43187", "127.0.0.1:55555"},
		{"port wins over prev", initResetOptions{port: 43195}, "127.0.0.1:43187", "127.0.0.1:43195"},
		{"prev plist used when nothing explicit", initResetOptions{}, "127.0.0.1:43187", "127.0.0.1:43187"},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			got, err := pickInitResetAPIAddr(tc.opts, tc.prev)
			if err != nil {
				t.Fatalf("err: %v", err)
			}
			if got != tc.want {
				t.Fatalf("expected %q, got %q", tc.want, got)
			}
		})
	}
}

func TestRunInitResetCommand_CallsRunnerThroughCobra(t *testing.T) {
	// Confirms `tars onboard reset` (alias) dispatches to the same
	// runner. Uses a minimal stub via initResetRunner.
	fakeHome := t.TempDir()
	t.Setenv("HOME", fakeHome)

	called := false
	prev := initResetRunner
	initResetRunner = func(_ context.Context, _ initResetOptions, _ io.Reader, _, _ io.Writer) error {
		called = true
		return nil
	}
	t.Cleanup(func() { initResetRunner = prev })

	cmd := newRootCommand(strings.NewReader(""), io.Discard, io.Discard)
	cmd.SetArgs([]string{"onboard", "reset", "--yes"})
	if err := cmd.Execute(); err != nil {
		t.Fatalf("onboard reset: %v", err)
	}
	if !called {
		t.Fatal("expected onboard reset to dispatch to initResetRunner")
	}
}
