func TestInitReset_PortInheritsFromExistingPlist(t *testing.T) {
	fakeHome := t.TempDir()
	t.Setenv("HOME", fakeHome)
	t.Setenv("TARS_PLUGINS_BUNDLED_DIR", filepath.Join(t.TempDir(), "no-such"))
	wsAbs := filepath.Join(fakeHome, ".tars", "workspace")
	_ = os.MkdirAll(wsAbs, 0o755)
	writeFakeOnboardingConfig(t, wsAbs)

	// Stage a plist that bakes --api-addr 127.0.0.1:43187 into the
	// ProgramArguments. Reset should reuse that addr instead of
	// auto-picking a different port.
	plistDir := filepath.Join(fakeHome, "Library", "LaunchAgents")
	_ = os.MkdirAll(plistDir, 0o755)
	plistPath := filepath.Join(plistDir, "io.tars.server.plist")
	plistBody := `<?xml version="1.0"?>
<plist version="1.0">
<dict>
  <key>ProgramArguments</key>
  <array>
    <string>/usr/local/bin/tars</string>
    <string>serve</string>
    <string>--config</string>
    <string>/tmp/tars-config.yaml</string>
    <string>--api-addr</string>
    <string>127.0.0.1:43187</string>
  </array>
</dict>
</plist>`
	if err := os.WriteFile(plistPath, []byte(plistBody), 0o644); err != nil {
		t.Fatalf("write plist: %v", err)
	}

	state := &initMockState{startResult: initStartResult{mode: "detached"}}
	swapInitResetHooks(t, state)
	initRuntimeGOOS = "linux" // skip launchd interaction; just check the addr threaded through

	var stdout strings.Builder
	cmd := newRootCommand(strings.NewReader(""), &stdout, io.Discard)
	cmd.SetArgs([]string{"init", "reset", "--yes", "--no-browser"})
	if err := cmd.Execute(); err != nil {
		t.Fatalf("init reset: %v", err)
	}

	if len(state.startCalls) != 1 {
		t.Fatalf("expected 1 start call, got %d", len(state.startCalls))
	}
	if state.startCalls[0].apiAddr != "127.0.0.1:43187" {
		t.Fatalf("expected port inherited from plist, got %q", state.startCalls[0].apiAddr)
	}
}

